#!/usr/bin/env python
"""Build requirements.txt from the *real* environment, not from memory.

Run this in the SAME environment that ran the notebook (e.g. a fresh Colab runtime after
"Restart and run all"):

    python tools/freeze_from_notebook.py notebooks/D2_Topic08_LeQuan.ipynb

It (1) parses every code cell and collects top-level imports, (2) maps them to PyPI
distribution names, (3) reads the installed version of each with importlib.metadata,
(4) writes requirements.txt and env_report.txt. Nothing is guessed: a package that is
imported but not installed is listed as MISSING and left out of requirements.txt.
"""
import ast, json, platform, sys
from importlib import metadata

# import name -> PyPI name, only where they differ
ALIASES = {"sklearn": "scikit-learn", "PIL": "Pillow", "cv2": "opencv-python",
           "yaml": "PyYAML", "bs4": "beautifulsoup4", "skimage": "scikit-image"}


def imports_from_notebook(path):
    nb = json.load(open(path, encoding="utf-8"))
    found = set()
    for cell in nb.get("cells", []):
        if cell.get("cell_type") != "code":
            continue
        src = "".join(cell["source"]) if isinstance(cell["source"], list) else cell["source"]
        # drop IPython magics / shell lines so ast can parse
        src = "\n".join("" if l.lstrip().startswith(("%", "!")) else l for l in src.splitlines())
        try:
            tree = ast.parse(src)
        except SyntaxError:
            print(f"[warn] could not parse a cell, skipped:\n{src[:80]!r}", file=sys.stderr)
            continue
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                found.update(a.name.split(".")[0] for a in node.names)
            elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                found.add(node.module.split(".")[0])
    return found


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    names = sorted(n for n in imports_from_notebook(sys.argv[1])
                   if n not in sys.stdlib_module_names)
    pinned, missing = [], []
    for n in names:
        dist = ALIASES.get(n, n)
        try:
            pinned.append(f"{dist}=={metadata.version(dist)}")
        except metadata.PackageNotFoundError:
            missing.append(n)

    py = platform.python_version()
    with open("requirements.txt", "w") as f:
        f.write(f"# Generated by tools/freeze_from_notebook.py on Python {py} ({platform.platform()})\n")
        f.write("\n".join(sorted(set(pinned), key=str.lower)) + "\n")
    with open("env_report.txt", "w") as f:
        f.write(f"python {py}\nplatform {platform.platform()}\n")
        f.write("imported third-party packages:\n  " + "\n  ".join(pinned) + "\n")
        if missing:
            f.write("MISSING (imported but not installed / name mismatch - check by hand):\n  "
                    + "\n  ".join(missing) + "\n")
    print(open("env_report.txt").read())


if __name__ == "__main__":
    main()
